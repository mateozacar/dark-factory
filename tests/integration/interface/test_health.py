class TestSettingsConfig:
    """
    Tests for dark_factory.config.Settings (pydantic-settings).

    I/O & Edge-Case Matrix — "Settings missing required var" row:
      Given: a required env var is absent with no default
      When:  Settings() is constructed
      Then:  pydantic ValidationError is raised

    I/O & Edge-Case Matrix — "App cold start, default env" row:
      Given: no .env file; usgs_base_url has a default
      When:  Settings() is constructed
      Then:  settings.usgs_base_url returns the USGS default URL
    """

    def test_settings_can_be_imported(self) -> None:
        from dark_factory.config import Settings  # noqa: F401  # ImportError until impl

    def test_settings_has_default_usgs_base_url(self) -> None:
        """
        Given: no environment override for USGS_BASE_URL
        When:  Settings() is instantiated
        Then:  usgs_base_url is the public USGS endpoint
        """
        # Ensure no override leaks from the environment during tests
        env_backup = os.environ.pop("USGS_BASE_URL", None)
        try:
            from dark_factory.config import Settings

            settings = Settings()
            assert settings.usgs_base_url == "https://earthquake.usgs.gov/fdsnws/event/1/"
        finally:
            if env_backup is not None:
                os.environ["USGS_BASE_URL"] = env_backup

    def test_settings_env_var_overrides_default(self, monkeypatch: pytest.MonkeyPatch) -> None:
        """
        Given: a .env / env var with USGS_BASE_URL overriding the default
        When:  Settings() is called
        Then:  the overridden value is returned by settings.usgs_base_url
        """
        custom_url = "https://mock-usgs.example.com/query"
        monkeypatch.setenv("USGS_BASE_URL", custom_url)

        # Re-import to pick up env change (pydantic-settings reads at construction time)
        from dark_factory.config import Settings

        settings = Settings()
        assert settings.usgs_base_url == custom_url
