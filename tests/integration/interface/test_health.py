class TestHealthEndpoint:
    """
    Given: the app is started with default settings (no .env file)
    When:  GET /health is requested via ASGITransport
    Then:  HTTP 200 is returned with {"status": "ok"}
    """

    @pytest.mark.anyio
    async def test_health_returns_200(self) -> None:
        """
        Given: create_app() is called with default Settings
        When:  GET /health is requested
        Then:  response status code is 200
        """
        import httpx
        from httpx import ASGITransport, AsyncClient

        from dark_factory.main import create_app  # ImportError until impl exists

        app = create_app()
        transport = ASGITransport(app=app)
        async with AsyncClient(transport=transport, base_url="http://testserver") as client:
            response = await client.get("/health")

        assert response.status_code == 200

    @pytest.mark.anyio
    async def test_health_returns_status_ok_body(self) -> None:
        """
        Given: create_app() is called with default Settings
        When:  GET /health is requested
        Then:  response JSON body contains {"status": "ok"}
        """
        import httpx
        from httpx import ASGITransport, AsyncClient

